// ====== TRANSLATION ENGINE ======
let currentLang = localStorage.getItem('mhc_lang') || 'en';

function t(key) {
  const entry = TRANSLATIONS[key];
  if (!entry) return key;
  return entry[currentLang] || entry['en'] || key;
}

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('mhc_lang', lang);
  document.documentElement.lang = lang === 'en' ? 'en' : lang === 'hi' ? 'hi' : 'mr';

  // Update all elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translation = t(key);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = translation;
    } else {
      el.innerHTML = translation;
    }
  });

  // Update language selector display
  const langDisplay = document.getElementById('lang-current');
  if (langDisplay) {
    const flags = { en: '🇬🇧', hi: '🇮🇳', mr: '🇮🇳' };
    const names = { en: 'EN', hi: 'हि', mr: 'मर' };
    langDisplay.innerHTML = `${flags[lang]} ${names[lang]}`;
  }

  // Highlight active language button
  document.querySelectorAll('.lang-option').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  // Trigger custom event so app.js can re-render dynamic content
  document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function toggleLangMenu() {
  const menu = document.getElementById('lang-dropdown');
  if (menu) menu.classList.toggle('show');
}

// Close lang menu on outside click
document.addEventListener('click', e => {
  if (!e.target.closest('.lang-switcher')) {
    const menu = document.getElementById('lang-dropdown');
    if (menu) menu.classList.remove('show');
  }
});

// Initialize on load
document.addEventListener('DOMContentLoaded', () => {
  // Apply saved language
  setLanguage(currentLang);
});
